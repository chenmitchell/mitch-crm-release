/**
 * 從 BCP 47 語言標籤取出預設國際冠碼。
 *
 * 取的是**地區子標籤**(de-DE 的 DE、zh-Hant-TW 的 TW),不是語言:
 * 語言與國家不是一對一(de 有德國、奧地利、瑞士三個冠碼),猜語言只會猜錯。
 * 標籤沒有地區子標籤(例如只填 `de`),或那個地區不在表裡,就回 undefined ——
 * 代表「沒有預設國碼」,電話比對會退回純數字比對,也就是可設定之前的行為。
 */
export function callingCodeForLocale(locale: string | null | undefined): string | undefined {
  const tag = (locale ?? '').trim();
  if (!tag) return undefined;
  // Intl 先做一次正規化(zh-hant-tw → zh-Hant-TW),失敗就退回原字串自己拆
  let canonical = tag;
  try {
    canonical = Intl.getCanonicalLocales(tag)[0] ?? tag;
  } catch {
    // 不合法的標籤照原樣拆,拆不到地區就回 undefined
  }
  for (const part of canonical.split(/[-_]/).slice(1)) {
    if (/^[A-Za-z]{2}$/.test(part)) return CALLING_CODE_BY_REGION[part.toUpperCase()];
  }
  return undefined;
}
