/**
 * `@mitchcrm/shared` —— 前後端共用的**出廠語彙**與**時間計算**。
 *
 * ## 這個套件的定位
 *
 * 只放「兩邊都必須拿到同一份答案,不然畫面與資料會對不上」的東西,而且限於兩類:
 *
 *   1. **出廠語彙**(`vocab/`):客戶階段、存證照片種類、場所類型、商業分類、互動管道
 *      的出廠預設,以及 `converted` / `dropped` / `visit` / `note` 這幾個產品保留字。
 *      後端第一次啟動 seed 進資料表用的是它,前端在設定 API 還沒回來時的保底值也是它。
 *      各抄一份的話,全新安裝的看板欄位、標籤與顏色會先畫成另一套再跳掉,
 *      而畫面上看不出原因。
 *
 *   2. **組織時區的日期計算**(`time/`):「今天是哪一天」「這一週從哪裡開始」。
 *      拜訪排程、日報、打卡核銷、地圖的今日視角、戰情圖表的期間起點、
 *      照片浮水印的時間戳全部走這一份,用 Intl 查時區資料庫,夏令時間也對。
 *
 *   3. **API 回應的形狀**(`api/`):後端答應在某一條路徑上給哪幾格欄位。
 *      只有 TypeScript 型別,編譯後不留任何執行期程式碼。後端拿它反推
 *      Prisma select 的最小集合,前端直接拿它當畫面型別,兩邊對同一份負責。
 *      理由與限制寫在下面那一節。
 *
 * ## `api/` 為什麼不算「這裡不放驗證 schema」的例外
 *
 * 這兩件事看起來很像,實際上守的是相反的方向,所以分開處理:
 *
 *   - **輸入驗證**(不放這裡)問的是「送進來的東西合不合法」。它有執行期行為、
 *     有錯誤訊息、有各自的邊界(後端要擋惡意輸入,前端要即時提示),
 *     兩邊本來就不該是同一份。共用一份的結果是規則慢慢走散,而走散不會有訊息。
 *   - **輸出形狀**(放這裡)問的是「後端會給哪幾格」。這件事**只有一個答案**,
 *     兩邊各寫一份就是有兩個答案。而兩個答案不一致時同樣不會有任何訊息:
 *     把後端 select 裡的一欄拿掉,型別檢查、單元測試、路徑探針全部照樣通過,
 *     畫面上那一格從此永遠是 undefined。這是這套系統唯一一個所有自動化守衛
 *     同時看不見的縫,`api/` 就是拿來補它的。
 *
 * 界線很清楚:`api/` 只放型別,一行執行期程式碼都不准進去。要驗證請回各自的
 * DTO 與表單。之前被整組移除的 `schemas/` 與 `types/` 是另一回事 ——
 * 那是一份 Zod schema 加一個 envelope 型別,全 repo 沒有任何一處 import,
 * 卻從這裡對外匯出,等於承諾一份沒有人用、也沒有測試的契約。
 * `api/` 相反:它的兩端都真的 import 它,而且後端那一側少一格就編譯不過。
 *
 * ## 這裡**不**放什麼
 *
 *   - **API 驗證 schema**。後端的驗證走 class-validator 的 DTO
 *     (`apps/backend/src` 底下各模組的 dto 目錄),前端表單各自驗。
 *     在這裡再放一份 Zod schema 的結果是兩份規則慢慢走散(理由見上一節)。
 *   - **可設定的值**。凡是後台改得動的(必拍清單、階段顯示名、地圖中心點),
 *     真相在資料庫,這裡最多放出廠預設。
 *   - **會碰 Prisma、Nest 或 React 的東西**。這個套件兩邊都要 import,
 *     所以只能是純函式、純型別與純資料。`api/` 的後端版型別用 `Date`,
 *     那是 JS 內建型別,不是 Prisma 的東西。
 *
 * ## 子路徑
 *
 * `@mitchcrm/shared` 匯出全部;`@mitchcrm/shared/vocab`、`@mitchcrm/shared/time`、
 * `@mitchcrm/shared/api` 與 `@mitchcrm/shared/password` 是同一份東西的分區入口。
 * 實務上呼叫端一律用根路徑,子路徑留著只是不擋人。
 *
 * `password.ts` 是第三類「兩邊必須拿到同一份答案」的東西:密碼長度規則。
 * 它不是驗證 schema(驗證仍在各自的 DTO 與表單裡),只是一組常數與一支純函式 ——
 * 三個地方各寫一個數字的結果,就是同一套系統對同一件事有三種規則。
 */
