/**
 * 全系統唯一一份密碼長度規則。
 *
 * ── 為什麼要有這一份 ────────────────────────────────────────────────
 * 同一套系統原本有三套不同的規則:安裝精靈要 12 個字元、邀請連結註冊要 8 個、
 * 改密碼也要 8 個。使用者看到的是「我設定的第一組密碼要 12 碼,可是進去之後
 * 改成 8 碼就過了」—— 規則等於形同虛設,而且沒有任何一頁說得出為什麼。
 *
 * ── 統一成哪一個 ────────────────────────────────────────────────────
 * 取最嚴的 12。理由:所有帳號都能看客戶資料與到訪座標,第一個管理員與後來加入的
 * 訪查人員在這件事上沒有等級差別,沒有理由讓後者寬鬆。往嚴的方向統一也不會把
 * 既有帳號鎖在外面 —— 登入不檢查長度,只有「設定新密碼」才走這條規則。
 *
 * ── 上限為什麼存在 ──────────────────────────────────────────────────
 * argon2 是刻意設計成慢的雜湊,沒有上限的話一則超長密碼就是一次可觀的 CPU 消耗,
 * 未登入就打得到的端點(邀請註冊)會變成放大攻擊的入口。
 *
 * 這一份只放常數與一支純函式:驗證仍然在各自的 DTO 與表單裡,
 * 兩邊引用同一個數字就不會再走散。
 */

/** 設定新密碼時的長度下限(字元數) */
export const PASSWORD_MIN = 12;

/** 設定新密碼時的長度上限(字元數) */
export const PASSWORD_MAX = 200;

/** 給使用者看的規則說明,表單提示與文件用同一句 */
export const PASSWORD_RULE_TEXT =
  `密碼至少 ${PASSWORD_MIN} 個字元,最多 ${PASSWORD_MAX} 個字元,` + '建議混用英文大小寫與數字。';

/** 長度不符時回一句中文訊息,符合就回 null */
export function passwordLengthError(password: string): string | null {
  if (password.length < PASSWORD_MIN) return `密碼至少 ${PASSWORD_MIN} 個字元`;
  if (password.length > PASSWORD_MAX) return `密碼最多 ${PASSWORD_MAX} 個字元`;
  return null;
}
